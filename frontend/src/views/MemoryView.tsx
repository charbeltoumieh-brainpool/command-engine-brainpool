function classifyVaultOrigin(note: {
  folder: string;
  slug: string;
  origin_kind?: VaultOriginKind | "human_wiki" | string;
  content_md?: string;
  excerpt?: string;
}): VaultOriginKind {
  if (note.origin_kind === "human_wiki") return "curated_unverified";
  if (
    note.origin_kind === "curated_unverified" ||
    note.origin_kind === "ai_compiled" ||
    note.origin_kind === "verified_human" ||
    note.origin_kind === "decision" ||
    note.origin_kind === "raw_evidence" ||
    note.origin_kind === "daily" ||
    note.origin_kind === "generated_ast"
  ) {
    return note.origin_kind;
  }

  const content = note.content_md || "";
  const excerpt = note.excerpt || "";
  const combined = `${content}\n${excerpt}`;

  if (
    content.includes("*Part of the graphify knowledge wiki") ||
    combined.includes("God node ·") ||
    combined.includes("Auto-generated by graphify") ||
    /^>\s*\d+\s+nodes\s+·\s+cohesion/m.test(combined) ||
    /\d+\s+nodes\s+·\s+cohesion/i.test(excerpt) ||
    GRAPHIFY_SLUG_PREFIXES.some((prefix) => note.slug.startsWith(prefix)) ||
    (content.includes("## Connections by Relation") && content.includes("`EXTRACTED`")) ||
    (excerpt.includes("`EXTRACTED`") && excerpt.includes("calls"))
  ) {
    return "generated_ast";
  }
  if (note.folder === "decisions") return "decision";
  if (note.folder === "raw") return "raw_evidence";
  if (note.folder === "daily") return "daily";
  return "curated_unverified";
}

function slugify(text: string): string {
  return (
    text
      .toLowerCase()
      .trim()
      .replace(/[^a-z0-9\-_]+/g, "-")
      .replace(/^-+|-+$/g, "") || `note-${Date.now()}`
  );
}

function parseVaultTarget(
  raw: string,
  notes: VaultNoteSummary[]
): { folder: string; slug: string } | null {
  const cleaned = raw.trim().replace(/^vault:\/\//i, "").replace(/^\/+/, "");
  if (!cleaned) return null;

  if (cleaned.includes("/")) {
    const [folder, ...rest] = cleaned.split("/");
    const slug = rest.join("/").replace(/\.md$/i, "");
    if (folder && slug) return { folder, slug };
  }

  const normalized = cleaned.replace(/\.md$/i, "").toLowerCase();
  const bySlug = notes.find((n) => n.slug.toLowerCase() === normalized);
  if (bySlug) return { folder: bySlug.folder, slug: bySlug.slug };

  const byTitle = notes.find((n) => n.title.toLowerCase() === normalized);
  if (byTitle) return { folder: byTitle.folder, slug: byTitle.slug };

  return { folder: "wiki", slug: slugify(cleaned) };
}

function normalizeBacklink(raw: unknown): NormalizedLinkRef | null {
  if (typeof raw === "string") {
    const trimmed = raw.trim();
    if (!trimmed) return null;
    return { key: trimmed, label: trimmed, target: trimmed };
  }
  if (raw && typeof raw === "object") {
    const obj = raw as { slug?: unknown; folder?: unknown; title?: unknown };
    const slug = typeof obj.slug === "string" ? obj.slug.trim() : "";
    const folder = typeof obj.folder === "string" ? obj.folder.trim() : "";
    const title = typeof obj.title === "string" ? obj.title.trim() : "";
    if (!slug) return null;
    const target = folder ? `${folder}/${slug}` : slug;
    return { key: target, label: title || slug, target };
  }
  return null;
}

/**
 * In Read mode, strips a leading `# Title` line if it duplicates `noteTitle`,
 * plus an immediately following `#tag1 #tag2` metadata line if present.
 * Leaves raw markdown untouched in Edit mode.
 */
function stripDuplicateHeaderForRead(markdown: string, noteTitle: string): string {
  const lines = markdown.replace(/\r\n?/g, "\n").split("\n");
  let idx = 0;

  while (idx < lines.length && lines[idx].trim() === "") {
    idx++;
  }

  // Strip optional HTML origin comment at top
  while (idx < lines.length && /^<!--\s*origin:[\s\S]*?-->$/i.test(lines[idx].trim())) {
    idx++;
    while (idx < lines.length && lines[idx].trim() === "") idx++;
  }

  if (idx < lines.length) {
    const first = lines[idx].trim();
    const h1Match = first.match(/^#\s+(.+)$/);
    if (h1Match) {
      const headingText = h1Match[1].trim().toLowerCase();
      const targetTitle = noteTitle.trim().toLowerCase();
      if (!targetTitle || headingText === targetTitle) {
        idx++;
        while (idx < lines.length && lines[idx].trim() === "") {
          idx++;
        }
      }
    }
  }

  if (idx < lines.length) {
    const maybeTags = lines[idx].trim();
    if (/^(?:#[a-zA-Z0-9_-]+(?:\s+|$))+$/.test(maybeTags)) {
      idx++;
      while (idx < lines.length && lines[idx].trim() === "") {
        idx++;
      }
    }
  }

  return lines.slice(idx).join("\n");
}

function triggerMarkdownDownload(filename: string, content: string) {
  const safeName = filename.endsWith(".md") ? filename : `${filename}.md`;
  const blob = new Blob([content], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = safeName;
  document.body.appendChild(a);
  a.click();
  a.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

